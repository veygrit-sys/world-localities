"""Render the human country index from its machine-readable catalogs."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
STATES = {'format_only': '住所形式のみ', 'partial_observations': '限定的な記録',
          'source_layers_available': '原典レイヤーあり'}


def render(root=ROOT):
    catalog = json.loads((root / 'countries/catalog.json').read_text())
    modules = {entry['code']: entry for entry in json.loads((root / 'countries/modules.json').read_text())['countries']}
    lines = ['# 国・地域から探す', '',
             '既存の世界監査表にある250の収集コードを管理しています。主権国家数や全国網羅済みの国数ではありません。', '',
             '国と原典・共有入力・検査の対応は [modules.json](modules.json)、保存パス・配布先の管理は [catalog.json](catalog.json) を参照してください。件数は出典別に確認し、重複する原典を合算しません。', '',
             '```bash', 'python -m localities country inspect --country JP',
             'python -m localities country verify --country JP', '```', '',
             '状態は保存済み原典の有無と範囲を表します。最新性、全国完全性、精度、配達可能性の評価とは別です。[更新・配布の方法](../docs/country-modules.md)', '',
             '<!-- Generated by python scripts/render_country_index.py; use --check to detect drift. -->', '',
             '| コード | 国・地域 | 状態 | 既存データへの入口 |', '|---|---|---|---|']
    for entry in catalog['countries']:
        code = entry['code']
        candidates = []
        for name in entry['paths']:
            parts = Path(name).parts
            if code in parts[:-1]:
                target = '/'.join(parts[:parts.index(code) + 1])
            else:
                target = name
            if target not in candidates:
                candidates.append(target)
        links = '、'.join(f'[{name}](../{name})' for name in candidates[:3]) or '国別inspectで住所形式・未取得を確認'
        if len(candidates) > 3:
            links += '（全参照は台帳）'
        state = STATES.get(modules[code]['inventory_state'], modules[code]['inventory_state'])
        lines.append(f"| `{code}` | {entry['name']} | {state} | {links} |")
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if (ROOT / 'countries/README.md').read_text() != expected:
            parser.exit(1, 'Country index is stale; regenerate with python scripts/render_country_index.py > countries/README.md\n')
        print('country index matches catalogs')
    else:
        print(expected, end='')
